#!/usr/bin/env python3
"""Build and align Skyrim skin vertex normals without changing mesh geometry.

The body generated by some BodySlide projects can omit VF_NORMAL/VF_TANGENT
from the main skin shape.  This tool restores those packed attributes, builds
area-weighted smooth normals, and gives coincident wrist/ankle vertices one
shared normal.  At the COtR neck, the body ring is matched to the geometric
normal calculated from the base head TRI (the head NIF has no static positions
or normals of its own).

Only the named BSTriShape vertex descriptors and packed normal/tangent fields
are changed. Positions, UVs, triangles, skin weights, bone indices, shaders,
extra shapes, and TRI files are left untouched.
"""

from __future__ import annotations

import argparse
import json
import os
import struct
import sys
from pathlib import Path

import numpy as np
from scipy.spatial import cKDTree


NIFTOOLS = os.path.join(
    os.environ["APPDATA"],
    "Blender Foundation",
    "Blender",
    "4.4",
    "scripts",
    "addons",
    "io_scene_niftools",
    "dependencies",
)
sys.path.insert(0, NIFTOOLS)

import nifgen.formats.nif as NifFormat  # noqa: E402
from nifgen.formats.nif import classes as NifClasses  # noqa: E402


NORMALS = 1 << 3
TANGENTS = 1 << 4
DESC_ATTR_SHIFT = 44
DESC_ATTR_MASK = 0xFFF << DESC_ATTR_SHIFT


def decode_name(value) -> str:
    if isinstance(value, bytes):
        return value.decode("utf-8", errors="replace")
    return str(value)


def normalize(vectors: np.ndarray) -> np.ndarray:
    lengths = np.linalg.norm(vectors, axis=1, keepdims=True)
    good = lengths[:, 0] > 1.0e-12
    result = vectors.copy()
    result[good] /= lengths[good]
    result[~good] = (0.0, 0.0, 1.0)
    return result


def geometric_normals(vertices: np.ndarray, triangles: np.ndarray) -> np.ndarray:
    result = np.zeros_like(vertices, dtype=np.float64)
    a = vertices[triangles[:, 0]].astype(np.float64)
    b = vertices[triangles[:, 1]].astype(np.float64)
    c = vertices[triangles[:, 2]].astype(np.float64)
    face = np.cross(b - a, c - a)
    np.add.at(result, triangles[:, 0], face)
    np.add.at(result, triangles[:, 1], face)
    np.add.at(result, triangles[:, 2], face)
    return normalize(result)


def tangent_frame(
    vertices: np.ndarray,
    uvs: np.ndarray,
    triangles: np.ndarray,
    normals: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    tan = np.zeros_like(vertices, dtype=np.float64)
    bitan = np.zeros_like(vertices, dtype=np.float64)
    for tri in triangles:
        i0, i1, i2 = (int(x) for x in tri)
        p0, p1, p2 = vertices[[i0, i1, i2]].astype(np.float64)
        uv0, uv1, uv2 = uvs[[i0, i1, i2]].astype(np.float64)
        e1, e2 = p1 - p0, p2 - p0
        d1, d2 = uv1 - uv0, uv2 - uv0
        det = d1[0] * d2[1] - d1[1] * d2[0]
        if abs(det) < 1.0e-12:
            continue
        inv = 1.0 / det
        t = (e1 * d2[1] - e2 * d1[1]) * inv
        b = (e2 * d1[0] - e1 * d2[0]) * inv
        tan[[i0, i1, i2]] += t
        bitan[[i0, i1, i2]] += b

    tan -= normals * np.sum(normals * tan, axis=1, keepdims=True)
    tan = normalize(tan)
    handed = np.sign(np.sum(np.cross(normals, tan) * bitan, axis=1))
    handed[handed == 0.0] = 1.0
    bitan = normalize(np.cross(normals, tan) * handed[:, None])
    return tan, bitan


def weld_duplicate_normals(vertices: np.ndarray, normals: np.ndarray, tol: float) -> None:
    keys = np.rint(vertices / tol).astype(np.int64)
    groups: dict[tuple[int, int, int], list[int]] = {}
    for index, key in enumerate(keys):
        groups.setdefault(tuple(int(x) for x in key), []).append(index)
    for indices in groups.values():
        if len(indices) < 2:
            continue
        shared = normalize(normals[indices].sum(axis=0, keepdims=True))[0]
        normals[indices] = shared


class Mesh:
    def __init__(self, path: Path, shape_name: str):
        self.path = path
        with path.open("rb") as stream:
            self.data = NifFormat.NifFile.from_stream(stream)
        matches = [
            block
            for root in self.data.roots
            for block in root.tree(unique=True)
            if isinstance(block, NifClasses.BSTriShape)
            and decode_name(block.name) == shape_name
        ]
        if len(matches) != 1:
            names = [
                decode_name(block.name)
                for root in self.data.roots
                for block in root.tree(unique=True)
                if isinstance(block, NifClasses.BSTriShape)
            ]
            raise RuntimeError(f"{path}: expected {shape_name!r}; found {names}")
        self.shape = matches[0]
        self.vertex_data = self.shape.get_vertex_data()
        self.vertices = np.asarray(
            [[float(v.vertex.x), float(v.vertex.y), float(v.vertex.z)] for v in self.vertex_data],
            dtype=np.float64,
        )
        self.uvs = np.asarray(
            [[float(v.uv.u), float(v.uv.v)] for v in self.vertex_data], dtype=np.float64
        )
        self.triangles = np.asarray(
            [[int(t.v_1), int(t.v_2), int(t.v_3)] for t in self.shape.get_triangles()],
            dtype=np.int32,
        )
        self.original_normals = np.asarray(
            [[float(v.normal.x), float(v.normal.y), float(v.normal.z)] for v in self.vertex_data],
            dtype=np.float64,
        )
        self.original_tangents = np.asarray(
            [[float(v.tangent.x), float(v.tangent.y), float(v.tangent.z)] for v in self.vertex_data],
            dtype=np.float64,
        )
        self.original_bitangents = np.asarray(
            [[float(v.bitangent_x), float(v.bitangent_y), float(v.bitangent_z)] for v in self.vertex_data],
            dtype=np.float64,
        )

    def enable_normal_fields(self) -> None:
        shape_desc = self.shape.vertex_desc
        partition = self.shape.skin.skin_partition
        old = int(partition.vertex_desc)
        attrs = ((old & DESC_ATTR_MASK) >> DESC_ATTR_SHIFT) | NORMALS | TANGENTS
        value = old & ~DESC_ATTR_MASK
        value = (value & ~0xF) | 10
        value = (value & ~(0xF << 16)) | (5 << 16)
        value = (value & ~(0xF << 20)) | (6 << 20)
        value = (value & ~(0xF << 28)) | (7 << 28)
        value = (value & ~DESC_ATTR_MASK) | (attrs << DESC_ATTR_SHIFT)
        desc_type = type(partition.vertex_desc)
        partition.vertex_desc = desc_type.from_value(value)
        self.shape.vertex_desc = type(shape_desc).from_value(value)
        partition.vertex_size = 40
        partition.data_size = len(self.vertex_data) * 40
        for vertex in self.vertex_data:
            vertex.arg = attrs

    def apply_frame(
        self,
        normals: np.ndarray,
        tangents: np.ndarray,
        bitangents: np.ndarray,
    ) -> None:
        self.enable_normal_fields()
        for vertex, normal, tangent, bitangent in zip(
            self.vertex_data, normals, tangents, bitangents
        ):
            vertex.normal.x, vertex.normal.y, vertex.normal.z = (float(x) for x in normal)
            vertex.tangent.x, vertex.tangent.y, vertex.tangent.z = (float(x) for x in tangent)
            vertex.bitangent_x = float(bitangent[0])
            vertex.bitangent_y = float(bitangent[1])
            vertex.bitangent_z = float(bitangent[2])

    def save(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("wb") as stream:
            NifFormat.NifFile.to_stream(self.data, stream)


def read_head_tri(path: Path) -> tuple[np.ndarray, np.ndarray]:
    raw = path.read_bytes()
    if raw[:8] != b"FRTRI003":
        raise RuntimeError(f"{path}: unsupported TRI signature {raw[:8]!r}")
    vertex_count = struct.unpack_from("<I", raw, 8)[0]
    meta = struct.unpack_from("<13I", raw, 12)
    triangle_count = meta[0]
    offset = 64
    vertices = np.asarray(
        struct.unpack_from(f"<{vertex_count * 3}f", raw, offset), dtype=np.float64
    ).reshape((-1, 3))
    offset += vertex_count * 12
    triangles = np.asarray(
        struct.unpack_from(f"<{triangle_count * 3}I", raw, offset), dtype=np.int32
    ).reshape((-1, 3))
    return vertices, triangles


def matched_pairs(a: np.ndarray, b: np.ndarray, tol: float) -> list[tuple[int, int]]:
    """Return every cross-mesh pair within tolerance, including split duplicates."""
    neighborhoods = cKDTree(a).query_ball_tree(cKDTree(b), tol)
    return [(i, int(j)) for i, js in enumerate(neighborhoods) for j in js]


def pair_components(pairs: list[tuple[int, int]]) -> list[tuple[list[int], list[int]]]:
    """Build connected components in a small bipartite seam graph."""
    left_to_right: dict[int, set[int]] = {}
    right_to_left: dict[int, set[int]] = {}
    for left, right in pairs:
        left_to_right.setdefault(left, set()).add(right)
        right_to_left.setdefault(right, set()).add(left)

    components = []
    unseen = set(left_to_right)
    while unseen:
        seed = unseen.pop()
        left_group = {seed}
        right_group: set[int] = set()
        pending_left = [seed]
        pending_right: list[int] = []
        while pending_left or pending_right:
            while pending_left:
                left = pending_left.pop()
                for right in left_to_right.get(left, ()):
                    if right not in right_group:
                        right_group.add(right)
                        pending_right.append(right)
            while pending_right:
                right = pending_right.pop()
                for left in right_to_left.get(right, ()):
                    if left not in left_group:
                        left_group.add(left)
                        unseen.discard(left)
                        pending_left.append(left)
        components.append((sorted(left_group), sorted(right_group)))
    return components


def share_pair_normals(
    left: np.ndarray,
    right: np.ndarray,
    pairs: list[tuple[int, int]],
) -> None:
    for left_indices, right_indices in pair_components(pairs):
        combined = left[left_indices].sum(axis=0) + right[right_indices].sum(axis=0)
        shared = normalize(combined.reshape(1, 3))[0]
        left[left_indices] = shared
        right[right_indices] = shared


def match_left_to_right(
    left: np.ndarray,
    right: np.ndarray,
    pairs: list[tuple[int, int]],
) -> None:
    """Copy the immutable right-side shading to each left seam component."""
    for left_indices, right_indices in pair_components(pairs):
        shared = normalize(right[right_indices].sum(axis=0, keepdims=True))[0]
        left[left_indices] = shared


def preserve_handed_frame(
    normals: np.ndarray,
    old_tangents: np.ndarray,
    old_bitangents: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    tangents = old_tangents - normals * np.sum(normals * old_tangents, axis=1, keepdims=True)
    tangents = normalize(tangents)
    handed = np.sign(np.sum(np.cross(normals, tangents) * old_bitangents, axis=1))
    handed[handed == 0.0] = 1.0
    bitangents = normalize(np.cross(normals, tangents) * handed[:, None])
    return tangents, bitangents


def update_selected_frame(
    normals: np.ndarray,
    tangents: np.ndarray,
    bitangents: np.ndarray,
    indices: set[int],
) -> tuple[np.ndarray, np.ndarray]:
    """Re-orthogonalize only edited seam vertices; preserve all other bytes."""
    result_t = tangents.copy()
    result_b = bitangents.copy()
    if not indices:
        return result_t, result_b
    selected = np.asarray(sorted(indices), dtype=np.int32)
    updated_t, updated_b = preserve_handed_frame(
        normals[selected], tangents[selected], bitangents[selected]
    )
    result_t[selected] = updated_t
    result_b[selected] = updated_b
    return result_t, result_b


def angle_stats(a: np.ndarray, b: np.ndarray, pairs: list[tuple[int, int]]) -> dict[str, float]:
    dots = np.asarray([np.clip(np.dot(a[i], b[j]), -1.0, 1.0) for i, j in pairs])
    angles = np.degrees(np.arccos(dots))
    return {
        "count": int(len(angles)),
        "mean": float(angles.mean()) if len(angles) else 0.0,
        "p95": float(np.percentile(angles, 95)) if len(angles) else 0.0,
        "max": float(angles.max()) if len(angles) else 0.0,
    }


def process_weight(
    body_path: Path,
    hands_path: Path,
    feet_path: Path,
    head_tri: Path,
    output: Path,
    tolerance: float,
    canonical_pairs: dict[str, list[tuple[int, int]]] | None = None,
) -> tuple[dict, dict[str, list[tuple[int, int]]]]:
    body = Mesh(body_path, "Softbody")
    hands = Mesh(hands_path, "Hands")
    feet = Mesh(feet_path, "Feet")

    body_normals = geometric_normals(body.vertices, body.triangles)
    weld_duplicate_normals(body.vertices, body_normals, tolerance)
    hands_normals = hands.original_normals.copy()
    feet_normals = feet.original_normals.copy()

    wrist = (canonical_pairs or {}).get("wrist") or matched_pairs(
        body.vertices, hands.vertices, tolerance
    )
    ankle = (canonical_pairs or {}).get("ankle") or matched_pairs(
        body.vertices, feet.vertices, tolerance
    )
    share_pair_normals(body_normals, hands_normals, wrist)
    share_pair_normals(body_normals, feet_normals, ankle)

    head_vertices, head_triangles = read_head_tri(head_tri)
    head_normals = geometric_normals(head_vertices, head_triangles)
    weld_duplicate_normals(head_vertices, head_normals, tolerance)
    neck = (canonical_pairs or {}).get("neck") or matched_pairs(
        body.vertices, head_vertices, tolerance
    )
    match_left_to_right(body_normals, head_normals, neck)

    body_tangents, body_bitangents = tangent_frame(
        body.vertices, body.uvs, body.triangles, body_normals
    )
    hands_tangents, hands_bitangents = update_selected_frame(
        hands_normals,
        hands.original_tangents,
        hands.original_bitangents,
        {right for _left, right in wrist},
    )
    feet_tangents, feet_bitangents = update_selected_frame(
        feet_normals,
        feet.original_tangents,
        feet.original_bitangents,
        {right for _left, right in ankle},
    )

    body.apply_frame(body_normals, body_tangents, body_bitangents)
    hands.apply_frame(hands_normals, hands_tangents, hands_bitangents)
    feet.apply_frame(feet_normals, feet_tangents, feet_bitangents)

    body.save(output / body_path.name)
    hands.save(output / hands_path.name)
    feet.save(output / feet_path.name)

    report = {
        "body": body_path.name,
        "wrist": angle_stats(body_normals, hands_normals, wrist),
        "ankle": angle_stats(body_normals, feet_normals, ankle),
        "neck": angle_stats(body_normals, head_normals, neck),
    }
    return report, {"wrist": wrist, "ankle": ankle, "neck": neck}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--head-tri", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--tolerance", type=float, default=0.001)
    args = parser.parse_args()

    # Weight 1 is the COtR-compatible endpoint whose neck ring coincides with
    # the base head TRI. The _0 files have identical topology but a displaced
    # neck in this particular BodySlide preset, so reuse the endpoint indices.
    report_1, canonical = process_weight(
        args.input / "femalebody_1.nif",
        args.input / "femalehands_1.nif",
        args.input / "femalefeet_1.nif",
        args.head_tri,
        args.output,
        args.tolerance,
    )
    report_0, _ = process_weight(
        args.input / "femalebody_0.nif",
        args.input / "femalehands_0.nif",
        args.input / "femalefeet_0.nif",
        args.head_tri,
        args.output,
        args.tolerance,
        canonical,
    )
    reports = [report_0, report_1]
    print(json.dumps(reports, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
